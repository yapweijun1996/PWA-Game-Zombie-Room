function detectLocale() {
  try {
    const saved = localStorage.getItem(STORAGE_KEY);
    if (saved && SUPPORTED_LOCALES.includes(saved)) return saved;
  } catch (_) {}
  const nav = (navigator.language || navigator.userLanguage || 'en').toLowerCase();
  for (const locale of SUPPORTED_LOCALES) {
    if (nav.startsWith(locale)) return locale;
  }
  if (nav.startsWith('zh')) return 'zh';
  return 'en';
}

let currentLocale = detectLocale();

export function getLocale() {
  return currentLocale;
}

export function setLocale(locale) {
  if (!SUPPORTED_LOCALES.includes(locale) || locale === currentLocale) return false;
  currentLocale = locale;
  try { localStorage.setItem(STORAGE_KEY, locale); } catch (_) {}
  return true;
}

export function t(key, params) {
  const table = dict[currentLocale] || dict.en;
  let str = table[key] ?? dict.en[key] ?? key;
  if (params) {
    for (const paramKey of Object.keys(params)) {
      str = str.split('{' + paramKey + '}').join(params[paramKey]);
    }
  }
  return str;
}
